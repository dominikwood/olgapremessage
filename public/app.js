// All three workbook columns contain these lessons; support and access differ.
const packageServiceGroups = {
  basics: ["oils", "calm", "legs", "hands", "head", "face", "neck", "morning"],
  rituals: ["home", "abhyanga", "legs", "body", "chest", "beliefs", "oils"],
  aroma: ["stress", "guide", "ritual", "movements"]
};
const packagePrices = { independent: 40, group: 200, advanced: 400 };

document.querySelectorAll("[data-package-services]").forEach((container) => {
  Object.entries(packageServiceGroups).forEach(([group, services]) => {
    const heading = document.createElement("h4");
    heading.dataset.i18n = `packages.${group}.title`;
    const list = document.createElement("ul");
    services.forEach((service) => {
      const item = document.createElement("li");
      item.dataset.i18n = `packages.${group}.${service}`;
      list.append(item);
    });
    container.append(heading, list);
  });
  const bonusTitle = document.createElement("h4");
  bonusTitle.dataset.i18n = "packages.bonus.title";
  const bonusText = document.createElement("p");
  bonusText.dataset.i18n = "packages.bonus.text";
  container.append(bonusTitle, bonusText);
});

const modal = document.querySelector("#lead-modal");
const selectedPackageEl = document.querySelector("#selected-package");
const form = document.querySelector("#lead-form");
const statusEl = document.querySelector("#form-status");
const openButtons = document.querySelectorAll("[data-open-modal]");
const closeButtons = document.querySelectorAll("[data-close-modal]");
const languageButtons = document.querySelectorAll("[data-lang-button]");

let currentLanguage = localStorage.getItem("site-language") || "uk";
let selectedPackage = null;

applyLanguage(currentLanguage);

languageButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.langButton));
});

openButtons.forEach((button) => {
  button.addEventListener("click", openModal);
});

closeButtons.forEach((button) => {
  button.addEventListener("click", closeModal);
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && !modal.hidden) {
    closeModal();
  }
});

form.addEventListener("submit", async (event) => {
  event.preventDefault();
  const submitButton = form.querySelector('[type="submit"]');
  if (submitButton.disabled) return;
  submitButton.disabled = true;
  submitButton.setAttribute("aria-busy", "true");
  setStatus(t("form.sending"));

  const formData = new FormData(form);
  const payload = {
    name: formData.get("name"),
    phone: formData.get("phone"),
    message: formData.get("message"),
    website: formData.get("website"),
    language: currentLanguage,
    source: selectedPackage ? packageLabel(selectedPackage) : t("cta.buy")
  };

  try {
    const response = await fetch("/api/apply", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload)
    });

    if (!response.ok) {
      throw new Error("Request failed");
    }

    form.reset();
    setStatus(t("form.success"), "success");
  } catch (error) {
    setStatus(t("form.error"), "error");
  } finally {
    submitButton.disabled = false;
    submitButton.removeAttribute("aria-busy");
  }
});

function applyLanguage(language) {
  currentLanguage = translations[language] ? language : "uk";
  localStorage.setItem("site-language", currentLanguage);
  document.documentElement.lang = currentLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    element.innerHTML = t(element.dataset.i18nHtml);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
  });

  languageButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.langButton === currentLanguage);
  });

  updateSelectedPackage();
  document.dispatchEvent(new CustomEvent("site-language-change"));

  if (statusEl.textContent) {
    statusEl.textContent = "";
    statusEl.className = "form-status";
  }
}

function t(key) {
  return translations[currentLanguage][key] || translations.uk[key] || key;
}

function packageLabel(packageId) {
  return `${t(`packages.${packageId}.title`)}: ${packagePrices[packageId]}\u00a0€`;
}

function updateSelectedPackage() {
  selectedPackageEl.hidden = !selectedPackage;
  selectedPackageEl.textContent = selectedPackage ? `${t("form.package")}: ${packageLabel(selectedPackage)}` : "";
}

function openModal(event) {
  const packageId = event.currentTarget.dataset.package;
  selectedPackage = Object.hasOwn(packagePrices, packageId) ? packageId : null;
  updateSelectedPackage();
  setStatus("");
  modal.hidden = false;
  document.body.style.overflow = "hidden";
  const firstInput = modal.querySelector("input");
  window.setTimeout(() => firstInput.focus(), 50);
}

function closeModal() {
  modal.hidden = true;
  document.body.style.overflow = "";
}

function setStatus(message, type) {
  statusEl.textContent = message;
  statusEl.className = "form-status";

  if (type) {
    statusEl.classList.add(`is-${type}`);
  }
}
